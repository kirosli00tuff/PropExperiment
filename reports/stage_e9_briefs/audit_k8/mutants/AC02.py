def previous_dates(dates: Sequence[date], d: date, k: int) -> tuple[date, ...]:
    """The ``k`` most recent elements of ``dates`` (sorted ascending) strictly before ``d``,
    oldest first; fewer when the table holds fewer, none when ``k`` <= 0."""
    lo, hi = 0, len(dates)
    while lo < hi:
        mid = (lo + hi) // 2
        if dates[mid] < d:
            lo = mid + 1
        else:
            hi = mid
    return tuple(dates[max(0, lo - k + 1):lo])


