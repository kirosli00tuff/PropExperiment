"""E29_tables.md from E29_cells.json (mechanical; the only judgement is the declaration's "beats B0" flag).

Usage (repo root): uv run python reports/stage_e29_briefs/work/basket/e29_tables.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import e29_basket as B  # noqa: E402

SRC = B.REPO / "reports" / "stage_e29_briefs" / "E29_cells.json"
OUT = B.REPO / "reports" / "stage_e29_briefs" / "E29_tables.md"
NR = "not run"


def num(v: Any) -> float:
    if v is None:
        return math.nan
    return math.inf if isinstance(v, str) else float(v)


def fx(v: Any, nd: int = 2) -> str:
    if v is None:
        return "-"
    if isinstance(v, str):
        return v
    return f"{v:.{nd}f}"


def key(firm: str, basket: str, setting: str, rho: float | None, case: str = "limit", form: str = "primary") -> str:
    r = "rNA" if rho is None else f"r{rho:.2f}"
    return f"{case}__{form}__{firm}__{basket}__{setting}__{r}"


def thr(c: dict[str, Any] | None) -> Any:
    if c is None:
        return None
    if c.get("status") != "computed":
        return c.get("status")
    return c["threshold"]["value"]


def x10(c: dict[str, Any] | None) -> Any:
    if c is None or c.get("status") != "computed":
        return None if c is None else c.get("status")
    return c["x10K"]["value"]


def cmp_b0(v: Any, b0: Any, setting: str) -> str:
    a, b = num(v), num(b0)
    if math.isnan(a) or math.isnan(b) or math.isinf(a) or math.isinf(b):
        return "-"
    return f"{a / b - 1:+.3f}" if setting == "i" else f"{a - b:+.2f}"


def beats(c: dict[str, Any] | None, b0: dict[str, Any] | None) -> str:
    """Section 7: break-even lower than B0's by more than the grid step and mu10K analogue not higher."""
    if c is None or b0 is None or c.get("status") != "computed" or b0.get("status") != "computed":
        return "-"
    t, tb = num(thr(c)), num(thr(b0))
    m, mb = num(x10(c)), num(x10(b0))
    if math.isinf(t):
        return "no"
    return "yes" if (t < tb - B.STEP - 1e-9 and m <= mb + 1e-9) else "no"


def firm_table(firm: str, cells: dict[str, dict[str, Any]]) -> list[str]:
    out = [f"### {firm}", "", "| basket | rho | setting | S USD | S/MLL | threshold | vs B0 | x10K | vs B0 (x10K) | "
           "cost/attempt USD | beats B0 |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for setting in ("i", "ii"):
        b0 = cells.get(key(firm, "B0", setting, None))
        for basket in B.BASKETS:
            for rho in ([None] if basket == "B0" else list(B.RHOS)):
                c = cells.get(key(firm, basket, setting, rho))
                if c is None:
                    out.append(f"| {basket} | {fx(rho)} | {setting} | {NR} | | | | | | | |")
                    continue
                cost = c.get("cost_per_attempt_usd")
                out.append(
                    f"| {basket} | {fx(rho)} | {setting} | {c['S_usd']:.1f} | {c['S_over_MLL']:.3f} | {fx(thr(c))} | "
                    f"{'-' if basket == 'B0' else cmp_b0(thr(c), thr(b0), setting)} | {fx(x10(c))} | "
                    f"{'-' if basket == 'B0' else cmp_b0(x10(c), x10(b0), setting)} | {fx(cost)} | "
                    f"{'-' if basket == 'B0' else beats(c, b0)} |")
    out += ["", "Reporting points (limit case): x, per-attempt pass rate, P(at least one payout per cycle), EV per "
                "cycle (USD).", "", "| basket | rho | setting | x | pass rate | P(payout) | EV |",
            "|---|---|---|---|---|---|---|"]
    for setting in ("i", "ii"):
        for basket in B.BASKETS:
            for rho in ([None] if basket == "B0" else list(B.RHOS)):
                c = cells.get(key(firm, basket, setting, rho))
                if c is None or c.get("status") != "computed":
                    continue
                for r in c["reporting"]:
                    out.append(f"| {basket} | {fx(rho)} | {setting} | {r['x']:.2f} | {r['p_pass_attempt']:.4f} | "
                               f"{r['p_any_payout']:.4f} | {r['ev']:.0f} |")
    return out + [""]


def main() -> int:
    d = json.loads(SRC.read_text())
    cells = {c["cell_id"]: c for c in d["cells"]}
    L = ["# Stage E.29 basket tables (generated by work/basket/e29_tables.py from E29_cells.json)", "",
         f"Declaration reports/stage_e29_model.md sha256 {d['declaration']['sha256']}; code fingerprint "
         f"{d['code_fingerprint']}; generated {d['generated_pdt']}.", "",
         "Every threshold below comes from E.28's bisection only (status 'bisection, unconfirmed'): the grid "
         "confirmation pass of A3_econ.md 2.4 was not run (lead's reduced scope, 21:55). "
         f"Cells on disk: {d['n_cells']}; tasks not run: {d['n_missing']} (rows marked '{NR}').", "",
         "Setting (i): threshold k* = smallest grid k with EV >= 0, every member at k mu*_alone; vs B0 = k*/k*(B0) - 1. "
         "Setting (ii): threshold mu*_QM (ticks), other members at mu = 0; vs B0 = difference in ticks. x10K: the "
         "mu10K analogue. beats B0 (section 7): threshold below B0's by more than 0.01 and x10K not higher.", "",
         "## B0 against E.28's QM pair (setting ii)", "", "| firm | E.28 mu*_lim / mu*_mkt / mu10K / cost | "
         "E.29 B0 | equal |", "|---|---|---|---|"]
    for r in d["b0_check"]:
        e, m = r["e28"], r.get("e29", {})
        L.append(f"| {r['firm']} | {e['mu_star_lim']} / {e['mu_star_mkt']} / {e['mu10K']} / "
                 f"{e['cost_per_attempt_usd']:.4f} | {m.get('mu_star_lim', NR)} / {m.get('mu_star_mkt', NR)} / "
                 f"{m.get('mu10K', NR)} / {fx(m.get('cost_per_attempt_usd'), 4)} | "
                 f"{r['equal'] if len(m) == 4 else 'pending: ' + ', '.join(sorted(set(e) - set(m))) + ' not run'} |")
    L += ["", "## Limit case per firm", ""]
    for f in B.FIRMS:
        L += firm_table(f, cells)
    L += ["## Best basket per firm (section 6 rule, from the limit cells at rho 0.5)", "",
          "| firm | best | ranking (basket: k*_i, mu*_QM_ii) |", "|---|---|---|"]
    for b in d["best_basket"]:
        rk = "; ".join(f"{r['basket']}: {fx(r['k_star_i'])}, {fx(r['mu_star_QM_ii'])}" for r in b["ranking"])
        L.append(f"| {b['firm']} | {b['best']} | {rk} |")
    if not d["best_basket"]:
        L.append(f"| all | {NR} | |")
    L += ["", "## Market case (c_i + S_rt,i; setting (i) k in units of mu*_mkt alone)", "",
          "| firm | basket | rho | setting | threshold | B0 threshold | vs B0 |", "|---|---|---|---|---|---|---|"]
    for c in d["cells"]:
        if c["case"] != "market" or c["basket"] == "B0":
            continue
        b0 = cells.get(key(c["firm"], "B0", c["setting"], None, "market"))
        L.append(f"| {c['firm']} | {c['basket']} | {fx(c['rho'])} | {c['setting']} | {fx(thr(c))} | {fx(thr(b0))} | "
                 f"{cmp_b0(thr(c), thr(b0), c['setting'])} |")
    for f in B.FIRMS:
        for s in ("i", "ii"):
            c = cells.get(key(f, "B0", s, None, "market"))
            L.append(f"| {f} | B0 | - | {s} | {fx(thr(c)) if c else NR} | | |")
    L += ["", "## Extended alone break-evens (E.28's single-pair model, 0 to 12 tick grid)", "",
          "| firm | code | E.28 mu*_lim / mu*_mkt | E.29 mu*_lim | E.29 mu*_mkt | status |", "|---|---|---|---|---|---|"]
    for a in d["alone"]:
        L.append(f"| {a['firm']} | {a['code']} | {a['e28']['mu_star_lim']} / {a['e28']['mu_star_mkt']} | "
                 f"{fx(a['limit']['mu_star'])} | {fx(a['market']['mu_star'])} | {a['limit']['status']} |")
    if not d["alone"]:
        L.append(f"| all | - | - | {NR} | {NR} | |")
    L += ["", "## Topstep B3 sensitivity (MGC dropped on funded days at the 2-lot XFA tier)", "",
          "| setting | rho | primary threshold | sensitivity threshold | primary x10K | sensitivity x10K |",
          "|---|---|---|---|---|---|"]
    for s in ("i", "ii"):
        for rho in B.RHOS:
            p = cells.get(key("topstep", "B3", s, rho))
            q = cells.get(key("topstep", "B3", s, rho, form="b3_sens"))
            L.append(f"| {s} | {rho:.2f} | {fx(thr(p)) if p else NR} | {fx(thr(q)) if q else NR} | "
                     f"{fx(x10(p)) if p else NR} | {fx(x10(q)) if q else NR} |")
    L += ["", "Share of Topstep B3 funded path-days at the 2-lot tier, primary form (law A every day):", "",
          "| setting | rho | x | share | funded path-days |", "|---|---|---|---|---|"]
    for s in ("i", "ii"):
        for rho in B.RHOS:
            p = cells.get(key("topstep", "B3", s, rho))
            for r in (p or {}).get("low_tier_primary", {}).get("rows", []):
                L.append(f"| {s} | {rho:.2f} | {r['x']:.2f} | {fx(r['share'], 4)} | {r['funded_days']} |")
    L += ["", "## Binding-limit log (section 4)", "",
          "| firm | basket | lots | firm cap (lots) | member product caps (contracts) | binding |", "|---|---|---|---|---|---|"]
    inputs = B.load_inputs()
    for f in B.FIRMS:
        for b, codes in B.BASKETS.items():
            caps = []
            for c in codes:
                pr = next(p for p in inputs["pairs"] if p["firm"] == f and p["code"] == c)
                caps.append(f"{c} {pr['position_limit']}")
            lots = B.basket_lots(codes)
            note = "no"
            if f == "topstep" and lots > 2:
                note = "Topstep XFA 2-lot tier: primary form skips/delays the third concurrent position; sensitivity above"
            L.append(f"| {f} | {b} | {lots:.1f} | {B.FIRM_CAP_LOTS[f]} | {', '.join(caps)} | {note} |")
    L += ["", "Topstep Tier 1 news window: every basket trades 1 contract per member (below the 3-contract micro cap) and "
          "schedules no opens in the 10-minute windows; applied as a scheduling constraint, non-binding on the P&L "
          "distribution (section 4).", ""]
    if d["missing"]:
        L += ["## Not run", ""] + [f"- {m if isinstance(m, str) else json.dumps(m)}" for m in d["missing"]] + [""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
